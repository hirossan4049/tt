import { createHash } from 'crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';
import sharp from 'sharp';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const JSON_PATH = join(ROOT, 'tomorrowland_tl26th_w1.json');
const OUT_DIR = join(ROOT, 'public', 'artists');
const MANIFEST_PATH = join(ROOT, 'src', 'lib', 'img-manifest.ts');

const SIZES = [
  { suffix: 'sm', width: 240 },
  { suffix: 'md', width: 480 },
  { suffix: 'lg', width: 960 },
];

const IMG_EXTS = new Set(['.jpg', '.jpeg', '.png', '.webp', '.gif', '.avif', '.bmp', '.tiff']);
function isImageUrl(url) {
  const u = url.split('?')[0].toLowerCase();
  const dot = u.lastIndexOf('.');
  return dot > 0 && IMG_EXTS.has(u.slice(dot));
}

const MUSIC_TERMS = [
  'dj', 'disc jockey', 'producer', 'music producer', 'musician', 'musical artist',
  'band', 'duo', 'music group', 'electronic', 'house', 'techno', 'trance', 'edm',
  'singer', 'songwriter', 'rapper', 'rock band', 'hip hop',
];

function isMusicPage(extract = '', title = '') {
  const text = `${extract} ${title}`.toLowerCase();
  return MUSIC_TERMS.some((t) => {
    if (/\s/.test(t)) return text.includes(t);
    return new RegExp(`\\b${t.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\b`).test(text);
  });
}

function sleep(ms) {
  return new Promise((r) => setTimeout(r, ms));
}

async function fetchWithRetry(url, retries = 3) {
  for (let i = 0; i < retries; i++) {
    const res = await fetch(url, {
      headers: { 'User-Agent': 'tt-image-fetcher/1.0 (research; contact: tt@h1rose.com)' },
    });
    if (res.status === 429) {
      const delay = 5000 * (i + 1);
      console.warn(`  429, waiting ${delay}ms...`);
      await sleep(delay);
      continue;
    }
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    return res.json();
  }
  throw new Error('HTTP 429 after retries');
}

function pageFromData(data) {
  const pages = data?.query?.pages;
  if (!pages) return null;
  return Object.values(pages)[0];
}

function titleRelevant(title, query) {
  const t = title.toLowerCase();
  const q = query.toLowerCase();
  if (t.includes(q)) return true;
  const words = q.split(/\s+/).filter((w) => w.length > 1);
  if (words.length > 1 && words.every((w) => t.includes(w))) return true;
  return false;
}

async function wikipediaImage(query) {
  const enc = encodeURIComponent(query);

  // 1. direct title (handles exact articles & redirects)
  const direct = await fetchWithRetry(
    `https://en.wikipedia.org/w/api.php?action=query&titles=${enc}&prop=pageimages|extracts&pithumbsize=1200&exintro=1&explaintext=1&format=json&redirects=1`,
  );
  const directPage = pageFromData(direct);
  if (directPage?.thumbnail?.source && isMusicPage(directPage.extract, directPage.title)) {
    return { source: directPage.thumbnail.source, page: directPage.title, via: 'wikipedia-direct', query };
  }

  // 2. search top result
  const search = await fetchWithRetry(
    `https://en.wikipedia.org/w/api.php?action=query&generator=search&gsrsearch=${enc}&gsrlimit=1&prop=pageimages|extracts&pithumbsize=1200&exintro=1&explaintext=1&format=json`,
  );
  const searchPage = pageFromData(search);
  if (
    searchPage?.thumbnail?.source &&
    isMusicPage(searchPage.extract, searchPage.title) &&
    titleRelevant(searchPage.title, query)
  ) {
    return { source: searchPage.thumbnail.source, page: searchPage.title, via: 'wikipedia-search', query };
  }

  return null;
}

function loadManifest() {
  if (!existsSync(MANIFEST_PATH)) return {};
  try {
    const code = readFileSync(MANIFEST_PATH, 'utf8');
    const json = code.replace(/^[\s\S]*?export const IMG_MANIFEST[\s\S]*?=\s*/, '').replace(/;\s*$/m, '');
    return JSON.parse(json);
  } catch (e) {
    console.error('manifest parse failed:', e.message);
    return {};
  }
}

function saveManifest(manifest) {
  writeFileSync(
    MANIFEST_PATH,
    `// Auto-generated by scripts/optimize-images.mjs\nexport const IMG_MANIFEST: Record<string, { sm: string; md: string; lg: string }> = ${JSON.stringify(manifest, null, 2)};\n`,
  );
}

async function download(url) {
  const res = await fetch(url, {
    headers: { 'User-Agent': 'tt-image-fetcher/1.0 (research; contact: tt@h1rose.com)' },
  });
  if (!res.ok) throw new Error(`HTTP ${res.status}`);
  return Buffer.from(await res.arrayBuffer());
}

function buildQueries(name) {
  const queries = [];
  const add = (q) => { if (q && !queries.includes(q)) queries.push(q); };

  add(name);

  const cleaned = name.replace(/[!.]+$/g, '').trim();
  if (cleaned !== name) add(cleaned);

  if (name.includes(' b2b ')) {
    name.split(' b2b ').forEach((s) => add(s.trim()));
  }

  const lower = name.toLowerCase();
  if (!lower.includes(' dj') && !lower.includes(' musician') && !lower.includes(' band')) {
    add(`${name} DJ`);
    add(`${name} musician`);
  }

  return queries;
}

async function main() {
  const data = JSON.parse(readFileSync(JSON_PATH, 'utf8'));
  mkdirSync(OUT_DIR, { recursive: true });
  const manifest = loadManifest();

  const missingNames = [
    ...new Set(data.performances.map((p) => p.name).filter((n) => !manifest[n])),
  ];

  const results = [];

  for (const name of missingNames) {
    if (name === 'More to be announced') {
      results.push({ name, status: 'skip' });
      continue;
    }

    const queries = buildQueries(name);
    let found = null;

    for (const q of queries) {
      try {
        found = await wikipediaImage(q);
      } catch (e) {
        console.warn('lookup error:', q, e.message);
      }
      if (found) break;
      await sleep(400);
    }

    if (!found) {
      results.push({ name, status: 'notfound' });
      console.log('not found:', name);
      await sleep(600);
      continue;
    }

    const { source, page, via, query } = found;
    if (!isImageUrl(source)) {
      results.push({ name, status: 'badext', url: source, page, via, query });
      console.log('bad ext:', name, source);
      await sleep(600);
      continue;
    }

    const hash = createHash('sha256').update(source.split('?')[0]).digest('hex').slice(0, 16);
    const base = `/artists/${hash}`;
    const paths = {};

    let buf;
    try {
      buf = await download(source);
    } catch (e) {
      results.push({ name, status: 'downloadfail', url: source, error: e.message, page, via, query });
      console.log('download fail:', name, e.message);
      await sleep(600);
      continue;
    }

    let metadata;
    try {
      metadata = await sharp(buf).metadata();
    } catch (e) {
      results.push({ name, status: 'sharpfail', url: source, error: e.message, page, via, query });
      console.log('sharp fail:', name, e.message);
      await sleep(600);
      continue;
    }

    const isAnimated = metadata.pages && metadata.pages > 1;

    try {
      for (const { suffix, width } of SIZES) {
        const outPath = join(OUT_DIR, `${hash}_${suffix}.webp`);
        await sharp(buf, { animated: isAnimated })
          .resize({ width, withoutEnlargement: true })
          .webp({ quality: suffix === 'sm' ? 75 : 82, effort: 4 })
          .toFile(outPath);
        paths[suffix] = `${base}_${suffix}.webp`;
      }
    } catch (e) {
      results.push({ name, status: 'resizefail', url: source, error: e.message, page, via, query });
      console.log('resize fail:', name, e.message);
      await sleep(600);
      continue;
    }

    manifest[name] = paths;
    results.push({ name, status: 'ok', url: source, page, via, query, paths });
    console.log('fetched', name, '=>', paths.md, `(${via} / ${page})`);
    await sleep(800);
  }

  saveManifest(manifest);

  writeFileSync(
    join(ROOT, 'scripts', 'fetch-wikipedia-images.results.json'),
    JSON.stringify(results, null, 2),
  );

  const ok = results.filter((r) => r.status === 'ok').length;
  const fail = results.filter((r) => r.status !== 'ok' && r.status !== 'skip').length;
  console.log(`[fetch-wikipedia-images] ok=${ok} fail=${fail} total=${results.length}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
