import { createHash } from 'crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';
import sharp from 'sharp';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const JSON_PATH = join(ROOT, 'tomorrowland_tl26th_w1.json');
const OUT_DIR = join(ROOT, 'public', 'artists');
const MANIFEST_PATH = join(ROOT, 'src', 'lib', 'img-manifest.ts');

const SIZES = [
  { suffix: 'sm', width: 240 },
  { suffix: 'md', width: 480 },
  { suffix: 'lg', width: 960 },
];

const IMG_EXTS = new Set(['.jpg', '.jpeg', '.png', '.webp', '.gif', '.avif', '.bmp', '.tiff']);
function isImageUrl(url) {
  const u = url.split('?')[0].toLowerCase();
  return IMG_EXTS.has(u.slice(u.lastIndexOf('.')));
}

async function download(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`failed ${url}: ${res.status}`);
  return Buffer.from(await res.arrayBuffer());
}

function loadManifest() {
  if (!existsSync(MANIFEST_PATH)) return {};
  try {
    const code = readFileSync(MANIFEST_PATH, 'utf8');
    const json = code.replace(/^[\s\S]*?export const IMG_MANIFEST\s*=\s*/, '').replace(/;\s*$/, '');
    return JSON.parse(json);
  } catch {
    return {};
  }
}

async function main() {
  const data = JSON.parse(readFileSync(JSON_PATH, 'utf8'));
  mkdirSync(OUT_DIR, { recursive: true });

  const manifest = loadManifest();
  const names = new Set(Object.keys(manifest));

  let done = 0;
  let skipped = 0;
  let failed = 0;

  for (const perf of data.performances) {
    const name = perf.name;
    if (names.has(name)) continue;

    const artist = perf.artists?.find((a) => a.image);
    if (!artist) {
      names.add(name);
      skipped++;
      continue;
    }

    const url = artist.image;
    if (!isImageUrl(url)) {
      failed++;
      continue;
    }
    const hash = createHash('sha256').update(url).digest('hex').slice(0, 16);
    const base = `/artists/${hash}`;
    const paths = {};

    let buf;
    try {
      buf = await download(url);
    } catch (e) {
      console.warn('download failed:', name, e.message);
      failed++;
      continue;
    }

    let metadata;
    try {
      metadata = await sharp(buf).metadata();
    } catch (e) {
      console.warn('unsupported format:', name, url, e.message);
      failed++;
      continue;
    }

    const isAnimated = metadata.pages && metadata.pages > 1;

    let wasMissing = false;
    try {
      for (const { suffix, width } of SIZES) {
        const outPath = join(OUT_DIR, `${hash}_${suffix}.webp`);
        if (!existsSync(outPath)) {
          wasMissing = true;
          await sharp(buf, { animated: isAnimated })
            .resize({ width, withoutEnlargement: true })
            .webp({ quality: suffix === 'sm' ? 75 : 82, effort: 4 })
            .toFile(outPath);
        }
        paths[suffix] = `${base}_${suffix}.webp`;
      }
    } catch (e) {
      console.warn('resize failed:', name, e.message);
      failed++;
      continue;
    }

    manifest[name] = paths;
    names.add(name);
    done++;
    if (wasMissing) console.log('optimized', name, Object.values(paths).join(' '));
  }

  writeFileSync(
    MANIFEST_PATH,
    `// Auto-generated by scripts/optimize-images.mjs\nexport const IMG_MANIFEST: Record<string, { sm: string; md: string; lg: string }> = ${JSON.stringify(manifest, null, 2)};\n`,
  );
  const total = Object.keys(manifest).length;
  if (done || skipped || failed) console.log(`[optimize-images] done=${done} skipped=${skipped} failed=${failed} total=${total}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
